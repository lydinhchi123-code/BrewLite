-- =====================================================
-- 1. TAO BANG DANH MUC
-- =====================================================

CREATE TABLE IF NOT EXISTS menu_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(120) NOT NULL UNIQUE,
    description TEXT,
    image_url TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =====================================================
-- 2. TAO BANG SAN PHAM
-- =====================================================

CREATE TABLE IF NOT EXISTS menu_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL
        REFERENCES menu_categories(id) ON DELETE RESTRICT,
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL UNIQUE,
    description TEXT,
    image_url TEXT,
    base_price NUMERIC(12,2) NOT NULL CHECK (base_price >= 0),
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_menu_products_category
    ON menu_products(category_id);

CREATE INDEX IF NOT EXISTS idx_menu_products_available
    ON menu_products(is_available);

-- =====================================================
-- 3. TAO BANG SIZE
-- =====================================================

CREATE TABLE IF NOT EXISTS menu_product_sizes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL
        REFERENCES menu_products(id) ON DELETE CASCADE,
    size_code VARCHAR(10) NOT NULL,
    size_name VARCHAR(50) NOT NULL,
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0,
    UNIQUE (product_id, size_code)
);

-- =====================================================
-- 4. TAO BANG TOPPING
-- =====================================================

CREATE TABLE IF NOT EXISTS menu_toppings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS menu_product_toppings (
    product_id BIGINT NOT NULL
        REFERENCES menu_products(id) ON DELETE CASCADE,
    topping_id BIGINT NOT NULL
        REFERENCES menu_toppings(id) ON DELETE CASCADE,
    PRIMARY KEY (product_id, topping_id)
);

