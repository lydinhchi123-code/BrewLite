-- =====================================================
-- 12. KIEM TRA SAN PHAM
-- =====================================================

SELECT
    p.id,
    p.name AS ten_mon,
    c.name AS danh_muc,
    p.base_price AS gia_goc,
    p.image_url AS hinh_anh,
    p.is_featured AS mon_noi_bat,
    p.is_available AS dang_ban
FROM menu_products p
JOIN menu_categories c ON c.id = p.category_id
ORDER BY c.display_order, p.display_order;

-- =====================================================
-- 13. KIEM TRA TOPPING
-- =====================================================

SELECT name, price, display_order
FROM menu_toppings
ORDER BY display_order;

-- =====================================================
-- 14. KIEM TRA TOPPING CUA SAN PHAM
-- =====================================================

SELECT
    p.name AS ten_mon,
    t.name AS topping,
    t.price AS gia_topping
FROM menu_product_toppings pt
JOIN menu_products p ON p.id = pt.product_id
JOIN menu_toppings t ON t.id = pt.topping_id
ORDER BY p.name, t.display_order;

-- =====================================================
-- 15. KIEM TRA BANH KHONG CO TOPPING
-- KET QUA MONG DOI: 0 DONG
-- =====================================================

SELECT p.name AS ten_banh, t.name AS topping
FROM menu_product_toppings pt
JOIN menu_products p ON p.id = pt.product_id
JOIN menu_categories c ON c.id = p.category_id
JOIN menu_toppings t ON t.id = pt.topping_id
WHERE c.slug = 'banh';

-- =====================================================
-- 16. KIEM TRA SIZE CUA TAT CA CAC MON
-- Mon nuoc mong doi co 3 size; mon banh khong co size
-- =====================================================

SELECT
    c.name AS danh_muc,
    p.name AS ten_mon,
    s.size_code,
    s.size_name,
    s.price AS gia_size
FROM menu_products p
JOIN menu_categories c ON c.id = p.category_id
LEFT JOIN menu_product_sizes s ON s.product_id = p.id
ORDER BY c.display_order, p.display_order, s.display_order;

-- Kiem tra tong so size theo mon nuoc
SELECT
    p.name AS ten_mon,
    COUNT(s.id) AS so_size
FROM menu_products p
JOIN menu_categories c ON c.id = p.category_id
LEFT JOIN menu_product_sizes s ON s.product_id = p.id
WHERE c.slug IN ('ca-phe', 'tra', 'tra-sua', 'da-xay')
GROUP BY p.id, p.name
ORDER BY p.name;

-- =====================================================
-- 17. Kiểm tra món và tồn kho
-- =====================================================
SELECT
    p.id,
    p.name,
    c.name AS category_name,
    p.stock_quantity,
    p.low_stock_threshold,
    p.track_inventory,
    p.is_available,
    CASE
        WHEN NOT p.track_inventory THEN 'KHONG_QUAN_LY_TON'
        WHEN p.stock_quantity = 0 THEN 'HET_HANG'
        WHEN p.stock_quantity <= p.low_stock_threshold THEN 'SAP_HET_HANG'
        ELSE 'CON_HANG'
    END AS stock_status
FROM menu_products p
JOIN menu_categories c ON c.id = p.category_id
ORDER BY c.display_order, p.display_order;


