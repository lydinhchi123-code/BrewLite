-- 4. TON KHO MAU
-- =====================================================

INSERT INTO ingredient_inventory
    (ingredient_id, stock_quantity, low_stock_threshold, updated_at)
SELECT
    i.id,
    CASE
        WHEN i.name = 'Đá viên' THEN 1000000
        ELSE COALESCE(p.quantity_per_package * 100, 100000)
    END,
    COALESCE(p.quantity_per_package * 10, 100),
    NOW()
FROM ingredients i
LEFT JOIN LATERAL (
    SELECT ip.quantity_per_package
    FROM ingredient_packaging ip
    WHERE ip.ingredient_id = i.id
      AND ip.is_active = TRUE
      AND ip.package_unit = i.base_unit
    ORDER BY ip.id
    LIMIT 1
) p ON TRUE
ON CONFLICT (ingredient_id) DO NOTHING;

