-- PHAN 1: TAO CAC BANG
-- ============================================================

CREATE TABLE ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    base_unit VARCHAR(10) NOT NULL
        CHECK (base_unit IN ('ml', 'g', 'cai')),
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE ingredient_packaging (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL
        REFERENCES ingredients(id) ON DELETE RESTRICT,
    package_name VARCHAR(50) NOT NULL,
    quantity_per_package NUMERIC(14,3) NOT NULL
        CHECK (quantity_per_package > 0),
    package_unit VARCHAR(10) NOT NULL
        CHECK (package_unit IN ('ml', 'g', 'cai')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (ingredient_id, package_name)
);

CREATE INDEX idx_ingredient_packaging_ingredient
    ON ingredient_packaging(ingredient_id);

CREATE TABLE ingredient_inventory (
    ingredient_id BIGINT PRIMARY KEY
        REFERENCES ingredients(id) ON DELETE RESTRICT,
    stock_quantity NUMERIC(14,3) NOT NULL DEFAULT 0
        CHECK (stock_quantity >= 0),
    low_stock_threshold NUMERIC(14,3) NOT NULL DEFAULT 0
        CHECK (low_stock_threshold >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL
        REFERENCES menu_products(id) ON DELETE RESTRICT,
    size_id BIGINT
        REFERENCES menu_product_sizes(id) ON DELETE RESTRICT,
    name VARCHAR(200) NOT NULL,
    version INTEGER NOT NULL DEFAULT 1
        CHECK (version > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (product_id, size_id, version)
);

CREATE INDEX idx_recipes_product ON recipes(product_id);
CREATE INDEX idx_recipes_size ON recipes(size_id);

CREATE UNIQUE INDEX uq_recipes_default_version
    ON recipes(product_id, version)
    WHERE size_id IS NULL;

CREATE TABLE recipe_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL
        REFERENCES recipes(id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL
        REFERENCES ingredients(id) ON DELETE RESTRICT,
    quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
    unit VARCHAR(10) NOT NULL
        CHECK (unit IN ('ml', 'g', 'cai')),
    notes TEXT,
    UNIQUE (recipe_id, ingredient_id)
);

CREATE INDEX idx_recipe_details_ingredient
    ON recipe_details(ingredient_id);

CREATE TABLE ingredient_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL
        REFERENCES ingredients(id) ON DELETE RESTRICT,
    transaction_type VARCHAR(20) NOT NULL
        CHECK (transaction_type IN (
            'IN', 'OUT', 'ADJUST_IN', 'ADJUST_OUT', 'WASTE'
        )),
    quantity NUMERIC(14,3) NOT NULL CHECK (quantity > 0),
    unit VARCHAR(10) NOT NULL
        CHECK (unit IN ('ml', 'g', 'cai')),
    reference_type VARCHAR(30),
    reference_id BIGINT,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_ingredient_transactions_date
    ON ingredient_transactions(ingredient_id, created_at DESC);


