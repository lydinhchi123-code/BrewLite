INSERT INTO recipe_steps (recipe_id, step_number, instruction)
SELECT
    r.id,
    sd.step_number,
    sd.instruction
FROM step_data sd
JOIN menu_products p ON p.slug = sd.product_slug
JOIN recipes r ON r.product_id = p.id
WHERE
    (
        p.slug IN (
            'ca-phe-sua-da', 'caramel-macchiato', 'americano', 'cappuccino',
            'tra-dao', 'tra-dau', 'tra-vai-lai', 'tra-chanh', 'tra-luu-do',
            'tra-sua-dau', 'tra-sua-thai-xanh', 'tra-sua-tran-chau',
            'matcha-da-xay', 'chocolate-da-xay', 'oreo-da-xay'
        )
        AND r.size_id IS NOT NULL
    )
    OR
    (
        p.slug IN ('banh-croissant', 'banh-kem-dau', 'banh-tart', 'tiramisu')
        AND r.size_id IS NULL
    )
ON CONFLICT (recipe_id, step_number)
DO UPDATE SET instruction = EXCLUDED.instruction;


-- 3. KIEM TRA DU LIEU 19 MON
SELECT
    p.name AS ten_mon,
    p.slug,
    s.size_code AS size,
    r.preparation_time AS thoi_gian_phut,
    COUNT(rs.id) AS so_buoc
FROM menu_products p
JOIN recipes r ON r.product_id = p.id
LEFT JOIN menu_product_sizes s ON s.id = r.size_id
LEFT JOIN recipe_steps rs ON rs.recipe_id = r.id
WHERE p.slug IN (
    'ca-phe-sua-da', 'caramel-macchiato', 'americano', 'cappuccino',
    'tra-dao', 'tra-dau', 'tra-vai-lai', 'tra-chanh', 'tra-luu-do',
    'tra-sua-dau', 'tra-sua-thai-xanh', 'tra-sua-tran-chau',
    'matcha-da-xay', 'chocolate-da-xay', 'oreo-da-xay',
    'banh-croissant', 'banh-kem-dau', 'banh-tart', 'tiramisu'
)
GROUP BY p.id, p.name, p.slug, s.size_code, r.id, r.preparation_time
ORDER BY p.name, s.size_code;


