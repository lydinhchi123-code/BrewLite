
BEGIN;

CREATE TABLE IF NOT EXISTS TaiKhoanKhachHang (
    makh BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hoten VARCHAR(100) NOT NULL,
    email VARCHAR(255),
    sodienthoai VARCHAR(20) NOT NULL,
    matkhauhash TEXT NOT NULL,
    trangthai SMALLINT NOT NULL DEFAULT 0
        CHECK (trangthai IN (0, 1)),
    ngaytao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ngaycapnhat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Cho phép email để trống nếu tài khoản chưa cung cấp email.
ALTER TABLE TaiKhoanKhachHang
    ALTER COLUMN email DROP NOT NULL;

-- Nếu bảng đã tồn tại, bảo đảm số điện thoại là bắt buộc.
-- Lệnh này yêu cầu các tài khoản cũ đều đã có số điện thoại.
ALTER TABLE TaiKhoanKhachHang
    ALTER COLUMN sodienthoai SET NOT NULL;

-- Không cho phép hai tài khoản sử dụng cùng số điện thoại.
CREATE UNIQUE INDEX IF NOT EXISTS
    uq_taikhoankhachhang_sodienthoai
ON TaiKhoanKhachHang (sodienthoai);

-- Email chỉ cần duy nhất khi được cung cấp.
CREATE UNIQUE INDEX IF NOT EXISTS
    uq_taikhoankhachhang_email
ON TaiKhoanKhachHang (email)
WHERE email IS NOT NULL;

COMMIT;

SELECT * FROM TaiKhoanKhachHang
ORDER BY makh;