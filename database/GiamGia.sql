CREATE TRIGGER trg_kiem_tra_su_dung_ma_giam_gia
BEFORE INSERT ON lich_su_su_dung_ma_giam_gia
FOR EACH ROW
EXECUTE FUNCTION fn_kiem_tra_su_dung_ma_giam_gia();


