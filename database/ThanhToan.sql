BEGIN;

-- Don hang duoc tao sau khi khach hang hoan tat buoc thanh toan.
CREATE TABLE IF NOT EXISTS DonHang (
    madonhang BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madonhanghienthi VARCHAR(30) NOT NULL UNIQUE,
    makh BIGINT REFERENCES TaiKhoanKhachHang(makh) ON DELETE SET NULL,
    hotennguoinhan VARCHAR(100) NOT NULL,
    sodienthoainguoinhan VARCHAR(20) NOT NULL,
    diachigiaohang TEXT NOT NULL,
    tinhthanh VARCHAR(100) NOT NULL,
    ghichu TEXT,
    tamtinh NUMERIC(12, 0) NOT NULL CHECK (tamtinh >= 0),
    phigiaohang NUMERIC(12, 0) NOT NULL DEFAULT 0 CHECK (phigiaohang >= 0),
    giamgia NUMERIC(12, 0) NOT NULL DEFAULT 0 CHECK (giamgia >= 0),
    tongtien NUMERIC(12, 0) NOT NULL CHECK (tongtien >= 0),
    magiamgia VARCHAR(50),
    trangthai VARCHAR(30) NOT NULL DEFAULT 'DA_TIEP_NHAN'
        CHECK (trangthai IN (
            'DA_TIEP_NHAN',
            'DANG_CHUAN_BI',
            'DANG_GIAO',
            'DA_GIAO',
            'DA_HUY'
        )),
    ngaydat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ngaycapnhat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_tongtien_hop_le
        CHECK (tongtien = tamtinh + phigiaohang - giamgia)
);

-- Luu snapshot ten va gia mon tai thoi diem dat hang,
-- tranh thay doi menu lam sai lich su don hang.
CREATE TABLE IF NOT EXISTS ChiTietDonHang (
    madonhang BIGINT NOT NULL REFERENCES DonHang(madonhang) ON DELETE CASCADE,
    stt SMALLINT NOT NULL CHECK (stt > 0),
    tenmon VARCHAR(150) NOT NULL,
    tuychon TEXT,
    soluong INTEGER NOT NULL CHECK (soluong > 0),
    dongia NUMERIC(12, 0) NOT NULL CHECK (dongia >= 0),
    thanhtien NUMERIC(12, 0) NOT NULL CHECK (thanhtien = soluong * dongia),
    PRIMARY KEY (madonhang, stt)
);

-- Moi don hang co toi da mot ban ghi thanh toan.
CREATE TABLE IF NOT EXISTS ThanhToan (
    mathanhtoan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madonhang BIGINT NOT NULL UNIQUE REFERENCES DonHang(madonhang) ON DELETE CASCADE,
    phuongthuc VARCHAR(20) NOT NULL
        CHECK (phuongthuc IN ('COD', 'BANKING', 'MOMO')),
    trangthai VARCHAR(20) NOT NULL DEFAULT 'CHO_THANH_TOAN'
        CHECK (trangthai IN ('CHO_THANH_TOAN', 'DA_THANH_TOAN', 'THAT_BAI', 'DA_HOAN')),
    sotien NUMERIC(12, 0) NOT NULL CHECK (sotien >= 0),
    matugiaodich VARCHAR(100) UNIQUE,
    ngaythanhtoan TIMESTAMPTZ,
    ngaycapnhat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_donhang_makh ON DonHang(makh);
CREATE INDEX IF NOT EXISTS idx_donhang_trangthai ON DonHang(trangthai);
CREATE INDEX IF NOT EXISTS idx_donhang_ngaydat ON DonHang(ngaydat DESC);
CREATE INDEX IF NOT EXISTS idx_thanhtoan_trangthai ON ThanhToan(trangthai);

COMMIT;