
BEGIN;

DROP TABLE IF EXISTS thanhtoan;
DROP TABLE IF EXISTS chitietdonhang;
DROP TABLE IF EXISTS donhang;

CREATE TABLE IF NOT EXISTS donhang (
    madonhang BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madonhanghienthi VARCHAR(30) NOT NULL UNIQUE,
    makh BIGINT REFERENCES taikhoankhachhang(makh) ON DELETE SET NULL,

    -- Thông tin người nhận
    hotennguoinhan VARCHAR(100) NOT NULL,
    sodienthoainguoinhan VARCHAR(20) NOT NULL,
    diachigiaohang TEXT NOT NULL,
    tinhthanh VARCHAR(100) NOT NULL,
    ghichu TEXT,

    -- Thông tin tiền
    tamtinh NUMERIC(12, 0) NOT NULL DEFAULT 0
        CHECK (tamtinh >= 0),
    phigiaohang NUMERIC(12, 0) NOT NULL DEFAULT 0
        CHECK (phigiaohang >= 0),
    giamgia NUMERIC(12, 0) NOT NULL DEFAULT 0
        CHECK (giamgia >= 0),
    tongtien NUMERIC(12, 0) NOT NULL DEFAULT 0
        CHECK (tongtien >= 0),
    magiamgia VARCHAR(50),

    -- Trạng thái đơn hàng
    trangthai VARCHAR(30) NOT NULL DEFAULT 'PENDING'
        CHECK (
            trangthai IN (
                'PENDING',
	            'PAID',
	            'PAYMENT_FAILED',
	            'PREPARING',
	            'READY',
	            'COMPLETED',
	            'CANCELLED'
            )
        ),

	-- Backend bật TRUE sau khi đã giữ/trừ kho thành công
    inventory_reserved BOOLEAN NOT NULL DEFAULT FALSE,
    -- Backend bật TRUE sau khi đã hoàn kho cho đơn hủy
    inventory_released BOOLEAN NOT NULL DEFAULT FALSE,

    ngaydat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ngaycapnhat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_tongtien_hop_le
        CHECK (tongtien = tamtinh + phigiaohang - giamgia),

	CONSTRAINT ck_inventory_release_requires_reservation
        CHECK (NOT inventory_released OR inventory_reserved)
);

CREATE TABLE IF NOT EXISTS chitietdonhang (
    mactdh BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madonhang BIGINT NOT NULL
        REFERENCES donhang(madonhang)
        ON DELETE CASCADE,
	product_id BIGINT
        REFERENCES menu_products(id) ON DELETE SET NULL,

    tenmon VARCHAR(255) NOT NULL,
    image_url TEXT,
    kichco VARCHAR(50),
    duong VARCHAR(50),
    da VARCHAR(50),
    topping TEXT,
    soluong INTEGER NOT NULL CHECK (soluong > 0),
    dongia NUMERIC(12, 0) NOT NULL CHECK (dongia >= 0),

	-- Backend bật TRUE khi số lượng chi tiết đã được trừ vào kho
    stock_deducted BOOLEAN NOT NULL DEFAULT FALSE,
	
    thanhtien NUMERIC(12, 0)
        GENERATED ALWAYS AS (soluong * dongia) STORED
);

CREATE TABLE IF NOT EXISTS thanhtoan (
    mathanhtoan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madonhang BIGINT NOT NULL UNIQUE
        REFERENCES donhang(madonhang)
        ON DELETE CASCADE,
    phuongthuc VARCHAR(20) NOT NULL
        CHECK (phuongthuc IN ('COD', 'BANKING', 'MOMO')),
    trangthai VARCHAR(20) NOT NULL DEFAULT 'CHO_THANH_TOAN'
        CHECK (
            trangthai IN (
                'CHO_THANH_TOAN',
                'DA_THANH_TOAN',
                'THAT_BAI',
                'DA_HOAN'
            )
        ),
    sotien NUMERIC(12, 0) NOT NULL CHECK (sotien >= 0),
    matugiaodich VARCHAR(100) UNIQUE,
	idempotency_key VARCHAR(100) UNIQUE,
    ngaythanhtoan TIMESTAMPTZ,
    ngaycapnhat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Các chỉ mục phục vụ truy vấn
CREATE INDEX idx_donhang_makh ON donhang(makh);
CREATE INDEX idx_donhang_trangthai ON donhang(trangthai);
CREATE INDEX idx_donhang_ngaydat ON donhang(ngaydat DESC);
CREATE INDEX idx_chitietdonhang_madonhang ON chitietdonhang(madonhang);
CREATE INDEX IF NOT EXISTS idx_chitietdonhang_product ON chitietdonhang(product_id);
CREATE INDEX idx_thanhtoan_trangthai ON thanhtoan(trangthai);

COMMIT;

SELECT *
FROM donhang
ORDER BY madonhang DESC
LIMIT 10;