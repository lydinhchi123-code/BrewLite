BEGIN;

-- Upgrade the earlier order-detail schema without dropping existing data or
-- columns. The NestJS order API uses these fields for inserts and history.
ALTER TABLE chitietdonhang
    ADD COLUMN IF NOT EXISTS mactdh BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN IF NOT EXISTS image_url TEXT,
    ADD COLUMN IF NOT EXISTS kichco VARCHAR(50),
    ADD COLUMN IF NOT EXISTS duong VARCHAR(50),
    ADD COLUMN IF NOT EXISTS da VARCHAR(50),
    ADD COLUMN IF NOT EXISTS topping TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS uq_chitietdonhang_mactdh
    ON chitietdonhang (mactdh);

-- Preserve the options from the previous schema in the new structured fields.
UPDATE chitietdonhang
SET kichco = COALESCE(
        kichco,
        NULLIF(btrim(substring(tuychon FROM 'Size:[[:space:]]*([^;]+)')), '')
    ),
    duong = COALESCE(
        duong,
        NULLIF(btrim(substring(tuychon FROM 'Đường:[[:space:]]*([^;]+)')), ''),
        NULLIF(btrim(substring(tuychon FROM 'Sugar:[[:space:]]*([^;]+)')), '')
    ),
    da = COALESCE(
        da,
        NULLIF(btrim(substring(tuychon FROM 'Đá:[[:space:]]*([^;]+)')), ''),
        NULLIF(btrim(substring(tuychon FROM 'Ice:[[:space:]]*([^;]+)')), '')
    ),
    topping = COALESCE(
        topping,
        NULLIF(btrim(substring(tuychon FROM 'Topping:[[:space:]]*([^;]+)')), '')
    );

COMMIT;
